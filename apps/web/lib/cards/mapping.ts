import type { DasAsset } from "./collection";

import catalogJson from "./catalog.generated.json";
import { speciesForCardName } from "./cardNames";

export type PowerTier = 1 | 2 | 3;

/** Fractions of the card image (0–1) where the creature art sits. Full-art cards use the whole card. */
export interface ArtWindow { x: number; y: number; w: number; h: number }

export interface CatalogEntry {
  id: string;
  set: string;
  setName: string;
  number: string;
  name: string;
  species: string;
  dex: number;
  level: number;
  tier: PowerTier;
  rarity: string | null;
  image: string;
  artWindow: ArtWindow;
}

export interface CardMappingEntry { species: string; level: number; tier: PowerTier }

interface Catalog { version: string; sets: { id: string; name: string; aliases: string[] }[]; entries: CatalogEntry[] }

/** Generated by scripts/build-card-catalog.mjs from the Pokémon TCG API. Rerun it to add sets. */
export const CARD_CATALOG = catalogJson as Catalog;

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const SET_BY_ALIAS = new Map(CARD_CATALOG.sets.flatMap((set) => set.aliases.map((a) => [norm(a), set.id] as const)));
const BY_KEY = new Map(CARD_CATALOG.entries.map((e) => [`${e.set}#${norm(e.number)}`, e]));

/** Reviewed card → battle definition table, keyed "<set id>#<number>". */
export const CARD_MAPPING: { version: string; entries: Record<string, CardMappingEntry> } = {
  version: CARD_CATALOG.version,
  entries: Object.fromEntries(CARD_CATALOG.entries.map((e) => [`${e.set}#${norm(e.number)}`, { species: e.species, level: e.level, tier: e.tier }])),
};

export function findCatalogEntry(setName: string | undefined, number: string | undefined): CatalogEntry | null {
  if (!setName || !number) return null;
  const set = SET_BY_ALIAS.get(norm(setName));
  return set ? BY_KEY.get(`${set}#${norm(number.split("/")[0])}`) ?? null : null;
}

export const FAUX_ART_WINDOW: ArtWindow = { x: 0.07, y: 0.13, w: 0.86, h: 0.37 };

/** A battle-ready pick: an owned card or a rental from the shared pool. */
export interface CardPick {
  key: string;
  species: string;
  label: string;
  image: string | null;
  grade: string | null;
  level: number;
  tier: PowerTier;
  rental: boolean;
  artWindow: ArtWindow;
}

export type CardResolution = { eligible: true; pick: CardPick } | { eligible: false; reason: string };

const attr = (a: DasAsset, trait: string) => a.content.metadata.attributes.find((x) => x.trait_type === trait)?.value;

export function resolveCard(asset: DasAsset): CardResolution {
  const category = attr(asset, "Category");
  if (category === "Trainer") return { eligible: false, reason: "Trainer cards can't battle" };
  if (category === "Energy") return { eligible: false, reason: "Energy cards can't battle" };
  if (category !== "Pokemon") return { eligible: false, reason: "Not a creature card" };
  const entry = findCatalogEntry(attr(asset, "Set"), attr(asset, "Card Number"));
  const grade = attr(asset, "Grade");
  if (!entry) return resolveByName(asset, grade);
  return {
    eligible: true,
    pick: {
      key: asset.id,
      species: entry.species,
      label: attr(asset, "Card Name") ?? entry.name,
      image: asset.content.links.image || entry.image,
      grade: grade ? `${attr(asset, "Grading Company") ?? ""} ${grade}`.trim() : null,
      level: entry.level,
      tier: entry.tier,
      rental: false,
      artWindow: entry.artWindow,
    },
  };
}

/**
 * A card outside the catalog: any Pokémon card still battles, as the Pokémon its
 * printed name identifies ("Dark Charizard" → Charizard). Its tier is the
 * species' tier, which is also what live-arena matchmaking uses.
 */
function resolveByName(asset: DasAsset, grade: string | undefined): CardResolution {
  const cardName = attr(asset, "Card Name") ?? asset.content.metadata.name;
  const named = cardName ? speciesForCardName(cardName) : null;
  if (!named) return { eligible: false, reason: "Not a recognised Pokémon" };
  return {
    eligible: true,
    pick: {
      key: asset.id,
      species: named.key,
      label: cardName ?? named.name,
      image: asset.content.links.image || null,
      grade: grade ? `${attr(asset, "Grading Company") ?? ""} ${grade}`.trim() : null,
      level: 50,
      tier: named.tier as PowerTier,
      rental: false,
      artWindow: FAUX_ART_WINDOW, // no art window on file; use the standard card layout
    },
  };
}

/** Same pool for both players, so squad depth never depends on collection size. */
export const RENTAL_POOL: CardPick[] = ["eevee", "lapras", "jolteon", "scyther", "onix", "hitmonchan"].map((species) => ({
  key: `rental-${species}`,
  species,
  label: species[0].toUpperCase() + species.slice(1),
  image: null,
  grade: null,
  level: 50,
  tier: 1,
  rental: true,
  artWindow: FAUX_ART_WINDOW,
}));

export type MatchFormat = "champion" | "squad";

export const FORMAT_LABEL: Record<MatchFormat, string> = { champion: "Champion 1v1", squad: "Squad of 3" };

/** Lead card first, then other owned cards, then rentals the player hasn't brought. */
export function buildTeam(lead: CardPick, owned: CardPick[], format: MatchFormat): CardPick[] {
  if (format === "champion") return [lead];
  const used = new Set([lead.species]);
  const bench: CardPick[] = [];
  for (const c of owned) if (bench.length < 2 && c.key !== lead.key && !used.has(c.species)) { bench.push(c); used.add(c.species); }
  for (const r of RENTAL_POOL) if (bench.length < 2 && !used.has(r.species)) { bench.push(r); used.add(r.species); }
  return [lead, ...bench];
}
