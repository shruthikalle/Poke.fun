"use client";

import { useCallback, useRef } from "react";
import type { BattleEvent, BattleState } from "../battle/types";
import { audioEngine, type SfxCue } from "./AudioEngine";
import { useAudio } from "./AudioProvider";

export type AudioCue = SfxCue;

export interface AudioCueProvider {
  play(cue: AudioCue): void;
  /** One-off clip by URL, e.g. a creature's cry. */
  playClip?(url: string): void;
  dispose?(): void;
}

type Tone = { freq: number; to?: number; dur: number; type?: OscillatorType; delay?: number; gain?: number };

const TONES: Partial<Record<AudioCue, Tone[]>> = {
  hit: [{ freq: 220, to: 90, dur: 0.12, type: "square", gain: 0.08 }],
  "super-hit": [{ freq: 330, to: 80, dur: 0.18, type: "sawtooth", gain: 0.08 }, { freq: 160, to: 60, dur: 0.12, type: "square", delay: 0.08, gain: 0.06 }],
  faint: [{ freq: 440, to: 70, dur: 0.6, type: "triangle", gain: 0.1 }],
  switch: [{ freq: 520, to: 880, dur: 0.09, type: "square", gain: 0.05 }],
  turn: [{ freq: 660, dur: 0.05, type: "sine", gain: 0.04 }],
  victory: [523, 659, 784, 1046].map((freq, i) => ({ freq, dur: 0.16, type: "square" as const, delay: i * 0.14, gain: 0.06 })),
  defeat: [392, 330, 262].map((freq, i) => ({ freq, dur: 0.22, type: "triangle" as const, delay: i * 0.2, gain: 0.08 })),
};

/** Synthesized tones; the fallback when a cue's sound file can't load. */
export class SynthAudioProvider implements AudioCueProvider {
  private ctx: AudioContext | null = null;

  play(cue: AudioCue) {
    try {
      const shared = audioEngine.output("sfx");
      const ctx = shared?.ctx ?? (this.ctx ??= new AudioContext());
      const out = shared?.node ?? ctx.destination;
      if (ctx.state === "suspended") void ctx.resume();
      for (const tone of TONES[cue] ?? []) {
        const start = ctx.currentTime + (tone.delay ?? 0);
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = tone.type ?? "square";
        osc.frequency.setValueAtTime(tone.freq, start);
        if (tone.to) osc.frequency.exponentialRampToValueAtTime(tone.to, start + tone.dur);
        gain.gain.setValueAtTime(tone.gain ?? 0.06, start);
        gain.gain.exponentialRampToValueAtTime(0.0001, start + tone.dur);
        osc.connect(gain).connect(out);
        osc.start(start);
        osc.stop(start + tone.dur + 0.02);
      }
    } catch {
      // Audio is decorative; ignore unsupported or blocked contexts.
    }
  }

  playClip(url: string) {
    try {
      const audio = new Audio(url);
      audio.volume = 0.5;
      void audio.play().catch(() => {});
    } catch {
      // Unsupported format or blocked autoplay; the clip is optional.
    }
  }

  dispose() {
    void this.ctx?.close();
    this.ctx = null;
  }
}

export function cueForEvent(event: BattleEvent, state: BattleState | null): AudioCue | null {
  switch (event.type) {
    case "damage":
      if (event.effectiveness === "immune") return null;
      if (event.crit) return "crit";
      return event.effectiveness === "super" ? "super-hit" : event.effectiveness === "resisted" ? "not-very-effective" : "hit";
    case "miss": return "miss";
    case "status": return "status";
    case "heal": return "heal";
    case "boost": return event.change > 0 ? "boost" : "drop";
    case "faint": return "faint";
    case "switch": return "switch";
    case "turn": return event.turn > 1 ? "turn" : null;
    case "win": return event.winner === state?.you ? "victory" : event.winner === "draw" ? null : "defeat";
    default: return null;
  }
}

/** Sound files for every cue (generated by scripts/build-audio.mjs), with the synth as fallback. */
export class SampleAudioProvider implements AudioCueProvider {
  private readonly synth = new SynthAudioProvider();

  play(cue: AudioCue) {
    if (audioEngine.settings.muted) return;
    void audioEngine.playSfx(cue).then((played) => { if (!played) this.synth.play(cue); });
  }

  playClip(url: string) {
    void audioEngine.playCry(url);
  }
}

/**
 * Battle sound cues backed by the app-wide AudioProvider, so mute and volume
 * are shared by every page. Pass a provider to route cues elsewhere.
 */
export function useBattleAudio(createProvider: () => AudioCueProvider = () => new SampleAudioProvider()) {
  const { settings, toggleMute } = useAudio();
  const provider = useRef<AudioCueProvider | null>(null);
  provider.current ??= createProvider();

  const play = useCallback((cue: AudioCue) => provider.current?.play(cue), []);
  const playClip = useCallback((url: string) => provider.current?.playClip?.(url), []);

  return { muted: settings.muted, toggleMute, play, playClip };
}
